"""Data warehouse layer: a star schema (`dwh`) built from the cleaned `kbo` tables.

    ZIP archives  ->  kbo.*  (cleaned copy of the source, one table per CSV)
                  ->  dwh.*  (dimensional model for reporting, e.g. Power BI)

Facts
    fact_enterprise      one row per active enterprise at the snapshot date
    fact_establishment   one row per establishment unit at the snapshot date
Dimensions (shared by both facts where it applies: conformed dimensions)
    dim_date, dim_geography, dim_activity, dim_juridical_form,
    dim_juridical_situation, dim_enterprise

Design rules applied here:
* Surrogate keys: every dimension has its own integer key; facts never join on KBO numbers.
* Stable keys: dimensions are upserted on their natural key, so a member keeps its
  surrogate key from one refresh to the next (slowly changing dimension, type 1:
  attributes are overwritten, no history is kept).
* Unknown member: key 0 exists in every dimension, so fact foreign keys are never NULL.
* Facts are a snapshot of the current extract: emptied and refilled at each refresh.
* The whole refresh is one transaction, and each one is recorded in dwh.etl_batch.

Run with the `kbo-warehouse` command after loading archives with `kbo`.
"""

import time

import psycopg
from psycopg.types.json import Jsonb

from kbo.load import _connect, current_extract_number
from kbo.runlog import logger as log, setup_logging

DIMENSIONS = [
    "dim_date",
    "dim_geography",
    "dim_activity",
    "dim_juridical_form",
    "dim_juridical_situation",
    "dim_enterprise",
]
FACTS = ["fact_enterprise", "fact_establishment"]

DDL = """
CREATE SCHEMA IF NOT EXISTS dwh;

CREATE TABLE IF NOT EXISTS dwh.dim_date (
    date_key INTEGER PRIMARY KEY,               -- YYYYMMDD; 0 = unknown
    full_date DATE UNIQUE,
    year SMALLINT,
    quarter SMALLINT,
    month SMALLINT,
    month_name TEXT,
    day SMALLINT,
    iso_weekday SMALLINT,                       -- 1 = Monday
    weekday_name TEXT,
    decade SMALLINT
);

CREATE TABLE IF NOT EXISTS dwh.dim_geography (
    geography_key INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    geography_hash TEXT NOT NULL UNIQUE,        -- natural key: hash of the 5 source columns
    zipcode TEXT,
    municipality_nl TEXT,
    municipality_fr TEXT,
    country_nl TEXT NOT NULL,
    country_fr TEXT NOT NULL,
    province TEXT NOT NULL,
    region TEXT NOT NULL,                       -- Brussels / Flanders / Wallonia / Abroad / Unknown
    is_belgium BOOLEAN NOT NULL
);

CREATE TABLE IF NOT EXISTS dwh.dim_activity (
    activity_key INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nace_code TEXT NOT NULL UNIQUE,             -- NACE-BEL 2025 subclass, 5 digits
    label_nl TEXT,
    label_fr TEXT,
    class_code TEXT,                            -- 4 digits
    class_label_nl TEXT,
    class_label_fr TEXT,
    group_code TEXT,                            -- 3 digits
    group_label_nl TEXT,
    group_label_fr TEXT,
    division_code TEXT,                         -- 2 digits
    division_label_nl TEXT,
    division_label_fr TEXT
);

CREATE TABLE IF NOT EXISTS dwh.dim_juridical_form (
    juridical_form_key INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    juridical_form_code TEXT NOT NULL UNIQUE,
    label_nl TEXT,
    label_fr TEXT
);

CREATE TABLE IF NOT EXISTS dwh.dim_juridical_situation (
    juridical_situation_key INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    juridical_situation_code TEXT NOT NULL UNIQUE,
    label_nl TEXT,
    label_fr TEXT
);

CREATE TABLE IF NOT EXISTS dwh.dim_enterprise (
    enterprise_key INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    enterprise_number TEXT NOT NULL UNIQUE,     -- natural (business) key
    name TEXT,
    enterprise_type_code TEXT,
    enterprise_type_nl TEXT,
    enterprise_type_fr TEXT,
    status_code TEXT,
    start_date DATE
);

CREATE TABLE IF NOT EXISTS dwh.fact_enterprise (
    enterprise_key INTEGER PRIMARY KEY REFERENCES dwh.dim_enterprise,
    start_date_key INTEGER NOT NULL REFERENCES dwh.dim_date,
    geography_key INTEGER NOT NULL REFERENCES dwh.dim_geography,          -- registered office
    main_activity_key INTEGER NOT NULL REFERENCES dwh.dim_activity,
    juridical_form_key INTEGER NOT NULL REFERENCES dwh.dim_juridical_form,
    juridical_situation_key INTEGER NOT NULL REFERENCES dwh.dim_juridical_situation,
    enterprise_count SMALLINT NOT NULL,         -- always 1: makes counting a plain SUM
    establishment_count INTEGER NOT NULL,
    has_email SMALLINT NOT NULL,                -- 0 / 1, additive
    has_phone SMALLINT NOT NULL,
    has_website SMALLINT NOT NULL,
    age_years SMALLINT                          -- at the snapshot date; not additive
);

CREATE TABLE IF NOT EXISTS dwh.fact_establishment (
    establishment_number TEXT PRIMARY KEY,      -- degenerate dimension
    enterprise_key INTEGER NOT NULL REFERENCES dwh.dim_enterprise,
    start_date_key INTEGER NOT NULL REFERENCES dwh.dim_date,
    geography_key INTEGER NOT NULL REFERENCES dwh.dim_geography,
    main_activity_key INTEGER NOT NULL REFERENCES dwh.dim_activity,
    establishment_count SMALLINT NOT NULL       -- always 1
);

CREATE INDEX IF NOT EXISTS fact_enterprise_geography ON dwh.fact_enterprise (geography_key);
CREATE INDEX IF NOT EXISTS fact_enterprise_activity ON dwh.fact_enterprise (main_activity_key);
CREATE INDEX IF NOT EXISTS fact_enterprise_start ON dwh.fact_enterprise (start_date_key);
CREATE INDEX IF NOT EXISTS fact_establishment_enterprise ON dwh.fact_establishment (enterprise_key);
CREATE INDEX IF NOT EXISTS fact_establishment_geography ON dwh.fact_establishment (geography_key);

CREATE TABLE IF NOT EXISTS dwh.etl_batch (
    batch_id INTEGER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    source_extract_number INTEGER NOT NULL,     -- kbo.meta ExtractNumber the facts reflect
    snapshot_date DATE,
    started_at TIMESTAMPTZ NOT NULL,
    finished_at TIMESTAMPTZ NOT NULL,
    row_counts JSONB NOT NULL
);
"""

# Hash of the address columns that identify a place. chr(31) cannot occur in the data,
# and the cleaned source has no empty strings, so NULL and '' cannot be confused.
_GEO_HASH = """md5(concat_ws(chr(31), coalesce({a}zipcode, ''), coalesce({a}municipality_nl, ''),
    coalesce({a}municipality_fr, ''), coalesce({a}country_nl, ''), coalesce({a}country_fr, '')))"""

# Belgian postal codes map to provinces by range. Applies only to Belgian addresses
# (the source leaves the country empty for those) with a regular 4-digit code.
_PROVINCE = """CASE
    WHEN country_nl IS NOT NULL THEN 'Abroad'
    WHEN zipcode !~ '^[0-9]{4}$' OR zipcode IS NULL THEN 'Unknown'
    WHEN zipcode::int BETWEEN 1000 AND 1299 THEN 'Brussels-Capital'
    WHEN zipcode::int BETWEEN 1300 AND 1499 THEN 'Walloon Brabant'
    WHEN zipcode::int BETWEEN 1500 AND 1999 THEN 'Flemish Brabant'
    WHEN zipcode::int BETWEEN 2000 AND 2999 THEN 'Antwerp'
    WHEN zipcode::int BETWEEN 3000 AND 3499 THEN 'Flemish Brabant'
    WHEN zipcode::int BETWEEN 3500 AND 3999 THEN 'Limburg'
    WHEN zipcode::int BETWEEN 4000 AND 4999 THEN 'Liège'
    WHEN zipcode::int BETWEEN 5000 AND 5999 THEN 'Namur'
    WHEN zipcode::int BETWEEN 6000 AND 6599 THEN 'Hainaut'
    WHEN zipcode::int BETWEEN 6600 AND 6999 THEN 'Luxembourg'
    WHEN zipcode::int BETWEEN 7000 AND 7999 THEN 'Hainaut'
    WHEN zipcode::int BETWEEN 8000 AND 8999 THEN 'West Flanders'
    WHEN zipcode::int BETWEEN 9000 AND 9999 THEN 'East Flanders'
    ELSE 'Unknown' END"""

_REGION = """CASE province
    WHEN 'Brussels-Capital' THEN 'Brussels'
    WHEN 'Walloon Brabant' THEN 'Wallonia' WHEN 'Liège' THEN 'Wallonia' WHEN 'Namur' THEN 'Wallonia'
    WHEN 'Hainaut' THEN 'Wallonia' WHEN 'Luxembourg' THEN 'Wallonia'
    WHEN 'Flemish Brabant' THEN 'Flanders' WHEN 'Antwerp' THEN 'Flanders' WHEN 'Limburg' THEN 'Flanders'
    WHEN 'West Flanders' THEN 'Flanders' WHEN 'East Flanders' THEN 'Flanders'
    ELSE province END"""


def _code_labels(category: str) -> str:
    """Sub-query giving (code, label_nl, label_fr) for one category of kbo.code."""
    return f"""(SELECT code,
            max(description) FILTER (WHERE language = 'NL') AS label_nl,
            max(description) FILTER (WHERE language = 'FR') AS label_fr
        FROM kbo.code WHERE category = '{category}' GROUP BY code)"""


# (description, SQL), run in this order inside one transaction.
STEPS: list[tuple[str, str]] = [
    # --- unknown members: key 0 in every dimension ------------------------------------
    (
        "unknown members",
        """
        INSERT INTO dwh.dim_date (date_key) VALUES (0) ON CONFLICT DO NOTHING;
        INSERT INTO dwh.dim_geography (geography_key, geography_hash, country_nl, country_fr,
                                       province, region, is_belgium)
            VALUES (0, 'UNKNOWN', 'Onbekend', 'Inconnu',
                    'Unknown', 'Unknown', false) ON CONFLICT DO NOTHING;
        INSERT INTO dwh.dim_activity (activity_key, nace_code, label_nl, label_fr)
            VALUES (0, 'UNKNOWN', 'Onbekend', 'Inconnu') ON CONFLICT DO NOTHING;
        INSERT INTO dwh.dim_juridical_form (juridical_form_key, juridical_form_code, label_nl, label_fr)
            VALUES (0, 'UNKNOWN', 'Onbekend / niet van toepassing', 'Inconnu / sans objet')
            ON CONFLICT DO NOTHING;
        INSERT INTO dwh.dim_juridical_situation
                (juridical_situation_key, juridical_situation_code, label_nl, label_fr)
            VALUES (0, 'UNKNOWN', 'Onbekend', 'Inconnu') ON CONFLICT DO NOTHING;
        INSERT INTO dwh.dim_enterprise (enterprise_key, enterprise_number, name)
            VALUES (0, 'UNKNOWN', 'Unknown enterprise') ON CONFLICT DO NOTHING;
        """,
    ),
    # --- dimensions: upsert on the natural key (SCD type 1) ---------------------------
    (
        "dim_date",
        """
        INSERT INTO dwh.dim_date
        SELECT to_char(d, 'YYYYMMDD')::int, d::date, extract(year FROM d), extract(quarter FROM d),
               extract(month FROM d), to_char(d, 'FMMonth'), extract(day FROM d),
               extract(isodow FROM d), to_char(d, 'FMDay'), (extract(year FROM d)::int / 10) * 10
        FROM generate_series(
            (SELECT least(min(e.start_date), (SELECT min(start_date) FROM kbo.establishment))
             FROM kbo.enterprise e),
            greatest(
                make_date(extract(year FROM current_date)::int, 12, 31),
                (SELECT max(start_date) FROM kbo.enterprise),
                (SELECT max(start_date) FROM kbo.establishment)),
            interval '1 day') AS d
        ON CONFLICT (date_key) DO NOTHING;
        """,
    ),
    (
        "dim_geography",
        f"""
        INSERT INTO dwh.dim_geography (geography_hash, zipcode, municipality_nl, municipality_fr,
                                       country_nl, country_fr, province, region, is_belgium)
        SELECT geography_hash, zipcode, municipality_nl, municipality_fr,
               coalesce(country_nl, 'België'), coalesce(country_fr, 'Belgique'),
               province, {_REGION}, country_nl IS NULL
        FROM (
            SELECT DISTINCT {_GEO_HASH.format(a="")} AS geography_hash,
                   zipcode, municipality_nl, municipality_fr, country_nl, country_fr,
                   {_PROVINCE} AS province
            FROM kbo.address
        ) places
        ON CONFLICT (geography_hash) DO UPDATE SET
            province = EXCLUDED.province, region = EXCLUDED.region;
        """,
    ),
    (
        "dim_activity",
        f"""
        WITH nace AS {_code_labels("Nace2025")}
        INSERT INTO dwh.dim_activity (nace_code, label_nl, label_fr, class_code, class_label_nl,
            class_label_fr, group_code, group_label_nl, group_label_fr, division_code,
            division_label_nl, division_label_fr)
        SELECT s.code, s.label_nl, s.label_fr,
               c.code, c.label_nl, c.label_fr,
               g.code, g.label_nl, g.label_fr,
               d.code, d.label_nl, d.label_fr
        FROM nace s
        LEFT JOIN nace c ON c.code = left(s.code, 4)
        LEFT JOIN nace g ON g.code = left(s.code, 3)
        LEFT JOIN nace d ON d.code = left(s.code, 2)
        WHERE s.code ~ '^[0-9]{{5}}$'
        ON CONFLICT (nace_code) DO UPDATE SET
            label_nl = EXCLUDED.label_nl, label_fr = EXCLUDED.label_fr,
            class_code = EXCLUDED.class_code, class_label_nl = EXCLUDED.class_label_nl,
            class_label_fr = EXCLUDED.class_label_fr, group_code = EXCLUDED.group_code,
            group_label_nl = EXCLUDED.group_label_nl, group_label_fr = EXCLUDED.group_label_fr,
            division_code = EXCLUDED.division_code, division_label_nl = EXCLUDED.division_label_nl,
            division_label_fr = EXCLUDED.division_label_fr;
        """,
    ),
    (
        "dim_juridical_form",
        f"""
        INSERT INTO dwh.dim_juridical_form (juridical_form_code, label_nl, label_fr)
        SELECT code, label_nl, label_fr FROM {_code_labels("JuridicalForm")} forms
        ON CONFLICT (juridical_form_code) DO UPDATE SET
            label_nl = EXCLUDED.label_nl, label_fr = EXCLUDED.label_fr;
        """,
    ),
    (
        "dim_juridical_situation",
        f"""
        INSERT INTO dwh.dim_juridical_situation (juridical_situation_code, label_nl, label_fr)
        SELECT code, label_nl, label_fr FROM {_code_labels("JuridicalSituation")} situations
        ON CONFLICT (juridical_situation_code) DO UPDATE SET
            label_nl = EXCLUDED.label_nl, label_fr = EXCLUDED.label_fr;
        """,
    ),
    (
        "dim_enterprise",
        f"""
        WITH names AS (
            -- one official name per enterprise; Dutch, then French, German, English
            SELECT DISTINCT ON (entity_number) entity_number, denomination
            FROM kbo.denomination
            WHERE type_of_denomination = '001'
            ORDER BY entity_number,
                     CASE language WHEN '2' THEN 1 WHEN '1' THEN 2 WHEN '3' THEN 3 WHEN '4' THEN 4 ELSE 5 END,
                     denomination
        )
        INSERT INTO dwh.dim_enterprise (enterprise_number, name, enterprise_type_code,
            enterprise_type_nl, enterprise_type_fr, status_code, start_date)
        SELECT e.enterprise_number, n.denomination, e.type_of_enterprise,
               t.label_nl, t.label_fr, e.status, e.start_date
        FROM kbo.enterprise e
        LEFT JOIN names n ON n.entity_number = e.enterprise_number
        LEFT JOIN {_code_labels("TypeOfEnterprise")} t ON t.code = e.type_of_enterprise
        ON CONFLICT (enterprise_number) DO UPDATE SET
            name = EXCLUDED.name, enterprise_type_code = EXCLUDED.enterprise_type_code,
            enterprise_type_nl = EXCLUDED.enterprise_type_nl,
            enterprise_type_fr = EXCLUDED.enterprise_type_fr,
            status_code = EXCLUDED.status_code, start_date = EXCLUDED.start_date;
        """,
    ),
    # --- helpers shared by both facts --------------------------------------------------
    (
        "main activity per entity",
        """
        CREATE TEMP TABLE main_activity ON COMMIT DROP AS
        SELECT DISTINCT ON (entity_number) entity_number, left(nace_code, 5) AS nace_code
        FROM kbo.activity
        WHERE nace_version = '2025' AND classification = 'MAIN'
        ORDER BY entity_number, activity_group, length(nace_code), nace_code;
        CREATE UNIQUE INDEX ON main_activity (entity_number);
        ANALYZE main_activity;
        """,
    ),
    (
        "place per address",
        f"""
        CREATE TEMP TABLE entity_place ON COMMIT DROP AS
        SELECT DISTINCT ON (a.entity_number) a.entity_number, g.geography_key
        FROM kbo.address a
        JOIN dwh.dim_geography g ON g.geography_hash = {_GEO_HASH.format(a="a.")}
        WHERE a.type_of_address IN ('REGO', 'BAET')
        ORDER BY a.entity_number, a.date_striking_off NULLS FIRST;
        CREATE UNIQUE INDEX ON entity_place (entity_number);
        ANALYZE entity_place;
        """,
    ),
    # --- facts: a snapshot of the current extract --------------------------------------
    ("empty facts", "TRUNCATE dwh.fact_enterprise, dwh.fact_establishment;"),
    (
        "fact_enterprise",
        """
        WITH snapshot AS (
            SELECT to_date(value, 'DD-MM-YYYY') AS day FROM kbo.meta WHERE variable = 'SnapshotDate'
        ), establishments AS (
            SELECT enterprise_number, count(*) AS n FROM kbo.establishment GROUP BY 1
        ), contacts AS (
            SELECT entity_number,
                   max((contact_type = 'EMAIL')::int) AS has_email,
                   max((contact_type = 'TEL')::int) AS has_phone,
                   max((contact_type = 'WEB')::int) AS has_website
            FROM kbo.contact WHERE entity_contact = 'ENT' GROUP BY 1
        )
        INSERT INTO dwh.fact_enterprise
        SELECT de.enterprise_key,
               coalesce(to_char(e.start_date, 'YYYYMMDD')::int, 0),
               coalesce(p.geography_key, 0),
               coalesce(da.activity_key, 0),
               coalesce(jf.juridical_form_key, 0),
               coalesce(js.juridical_situation_key, 0),
               1,
               coalesce(est.n, 0),
               coalesce(c.has_email, 0), coalesce(c.has_phone, 0), coalesce(c.has_website, 0),
               extract(year FROM age((SELECT day FROM snapshot), e.start_date))
        FROM kbo.enterprise e
        JOIN dwh.dim_enterprise de ON de.enterprise_number = e.enterprise_number
        LEFT JOIN entity_place p ON p.entity_number = e.enterprise_number
        LEFT JOIN main_activity ma ON ma.entity_number = e.enterprise_number
        LEFT JOIN dwh.dim_activity da ON da.nace_code = ma.nace_code
        LEFT JOIN dwh.dim_juridical_form jf ON jf.juridical_form_code = e.juridical_form
        LEFT JOIN dwh.dim_juridical_situation js ON js.juridical_situation_code = e.juridical_situation
        LEFT JOIN establishments est ON est.enterprise_number = e.enterprise_number
        LEFT JOIN contacts c ON c.entity_number = e.enterprise_number;
        """,
    ),
    (
        "fact_establishment",
        """
        INSERT INTO dwh.fact_establishment
        SELECT s.establishment_number,
               coalesce(de.enterprise_key, 0),
               coalesce(to_char(s.start_date, 'YYYYMMDD')::int, 0),
               coalesce(p.geography_key, 0),
               coalesce(da.activity_key, 0),
               1
        FROM kbo.establishment s
        LEFT JOIN dwh.dim_enterprise de ON de.enterprise_number = s.enterprise_number
        LEFT JOIN entity_place p ON p.entity_number = s.establishment_number
        LEFT JOIN main_activity ma ON ma.entity_number = s.establishment_number
        LEFT JOIN dwh.dim_activity da ON da.nace_code = ma.nace_code;
        """,
    ),
    ("statistics", "".join(f"ANALYZE dwh.{table};" for table in [*DIMENSIONS, *FACTS])),
]


def refresh_warehouse(conn: psycopg.Connection) -> dict[str, int]:
    """Rebuilds the facts and brings the dimensions up to date. Returns row counts per table.

    `conn` must be an autocommit connection (see `kbo.load._connect`); the refresh runs
    as a single transaction, so readers never see a half-built warehouse.
    """
    extract_number = current_extract_number(conn)
    if extract_number is None:
        raise RuntimeError("The kbo tables are empty: load a Full archive before building the warehouse.")

    log.info("Refreshing the data warehouse from extract %s", extract_number)
    with conn.transaction(), conn.cursor() as cur:
        cur.execute("SELECT now()")
        started_at = cur.fetchone()[0]
        cur.execute(DDL)

        for description, sql in STEPS:
            t0 = time.perf_counter()
            cur.execute(sql)
            log.info("%-28s %.1fs", description, time.perf_counter() - t0)

        counts = {}
        for table in [*DIMENSIONS, *FACTS]:
            cur.execute(f"SELECT count(*) FROM dwh.{table}")
            counts[table] = cur.fetchone()[0]

        cur.execute(
            """
            INSERT INTO dwh.etl_batch (source_extract_number, snapshot_date, started_at,
                                       finished_at, row_counts)
            VALUES (%s,
                    (SELECT to_date(value, 'DD-MM-YYYY') FROM kbo.meta WHERE variable = 'SnapshotDate'),
                    %s, clock_timestamp(), %s)
            """,
            (extract_number, started_at, Jsonb(counts)),
        )

    for table, count in counts.items():
        log.info("dwh.%-24s %s rows", table, f"{count:,}")
    return counts


def main() -> None:
    setup_logging()
    with _connect() as conn:
        refresh_warehouse(conn)


if __name__ == "__main__":
    main()
